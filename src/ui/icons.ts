/**
 * 建一个图标元素。
 *
 * ## 为什么返回 `SVGElement` 而不是字符串
 *
 * 字符串要 `innerHTML` 塞进去，而本工程有 `dom.ts` 的规矩：
 * **每帧只改内容，不重建 DOM**。返回节点让调用方把它 `appendChild` 一次，
 * 之后再也不碰它。
 *
 * ## 为什么 `aria-hidden`
 *
 * 图标本身**不是**给读屏器读的——它的语义由旁边那个按钮的 `aria-label` 给。
 * 图标若同时被读一遍，盲用户会听到「图形 图形 图形」，
 * 那比不读还糟。所以图标一律 `aria-hidden="true"`，
 * **无障碍名由按钮承担**（见 `iconButton()`）。
 *
 * @param name 图标名
 * @param cls 额外的类名（默认 `g-ic`）
 */
export function icon(name: IconName, cls = 'g-ic'): SVGElement {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('class', cls);
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  const paths = ICONS[name];
  for (const p of paths) {
    const el = document.createElementNS('http://www.w3.org/2000/svg', 'path');
    el.setAttribute('d', p.d);
    el.setAttribute('fill', p.fill ? 'currentColor' : 'none');
    el.setAttribute('stroke', p.fill ? 'none' : 'currentColor');
    el.setAttribute('stroke-width', '1.6');
    el.setAttribute('stroke-linecap', 'round');
    el.setAttribute('stroke-linejoin', 'round');
    svg.appendChild(el);
  }
  return svg;
}

/**
 * 建一颗**只有图标**的按钮。
 *
 * ## 无障碍名是必填的，不是可选的
 *
 * 一颗只有图形的按钮若没有 `aria-label`，读屏器只会念「按钮」——
 * 那是把「图标化」做成了「不可用」。
 * 所以这里**强制**要 `aria`：`aria` 缺失时抛错，
 * 而不是悄悄产出一颗没有名字的按钮。
 *
 * 理由是这一类 bug 在画面上完全看不出来：图标画得再好看，
 * 读屏器那边仍然是空的。而 `t()` 给出的名字会跟着语言切换，
 * 所以调用方应当把 `t('key_pause')` 这种**现成的键位文案**传进来。
 *
 * @param name 图标名
 * @param aria 无障碍名（**必填**）
 * @param title 悬停提示。缺省时用 `aria`。
 * @param cls 按钮的额外类名
 */
export function iconButton(
  name: IconName,
  aria: string,
  title?: string,
  cls = '',
): HTMLButtonElement {
  if (!aria) {
    // 抛出去而不是静默：见上面的说明。
    // ★ 这条消息是**开发者向**的（抛异常时只有跑它的人看得到），
    //   而「界面硬编码中文」那一门只放行登记在白名单里的中文。
    //   白名单**只能减不能增**，所以这里直接写英文。
    throw new Error(`[gift188] iconButton(${name}) needs a non-empty aria-label`);
  }
  const b = document.createElement('button');
  b.type = 'button';
  b.className = `g-btn g-ic-btn ${cls}`.trim();
  b.setAttribute('aria-label', aria);
  b.title = title ?? aria;
  b.appendChild(icon(name));
  return b;
}

