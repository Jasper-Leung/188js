/**
 * 图标 —— **零请求、零依赖**的一整套矢量图形。
 *
 * ## 为什么图标是内联 SVG，而不是字体或图片
 *
 * 这个工程有一条硬规矩：**整份 UI 不发一个图片请求**（见 `styles.css` 的文件头
 * 「零图片」）。理由是目标机器往往也是慢网络机器，而每多一个资源请求，
 * 首屏就多一次往返。所以这里不用图标字体（那是一整个 woff2），
 * 也不用 PNG/SVG 文件（那是 N 个请求）。
 *
 * 内联 SVG 是唯一同时满足「任意缩放不糊」与「零请求」的做法：
 * 路径直接进 DOM，跟着 `currentColor` 走，一份 CSS 变量换色。
 *
 * ## 形状为什么要自己画，而不是抄一份图标库
 *
 * 因为整套图标要在**同一个视觉语言**里：同一套圆角比例、同一套线宽、
 * 同一套「留白比图形更重」的密度。这里要的是
 * 「细线 + 圆头 + 大量留白」，不是某一个具体的路径。
 * 所以这里是按那三个规矩逐个画的。
 *
 * ## 与 `theme.ts` 的分工
 *
 * 本文件**只管形状**，不管颜色。颜色一律走 `currentColor`，
 * 由 CSS 决定（`.g-ic` 继承按钮的文字色），
 * 于是「图标」这一层永远不会出现「图标是灰的、字是金的」这种颜色打架。
 *
 * ## 尺寸
 *
 * 全部按 24×24 的画布画，描边宽度 1.6（`1.6/24` 的比例在 16px 下
 * 约合 1.07px，正好是发丝线又不至于断）。
 * 真正的显示尺寸由 CSS 的 `.g-ic` 决定，这里不写死。
 */

