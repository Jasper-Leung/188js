/**
 * 某个图标名是否存在。**给回归用**——
 * `icon()` 里 `ICONS[name]` 拼错会得到 `undefined`，
 * 而 `undefined.forEach` 抛的是「读 undefined 的属性」，看不出是哪个图标名错了。
 * 这里把它变成一句人话。
 */
export function hasIcon(name: string): boolean {
  return Object.prototype.hasOwnProperty.call(ICONS, name);
}
