/**
 * 五件乐事的颜色。
 *
 * 取自 chrome.ts 里五个小游戏的景（云影台的天光、茶烟小筑的桌面、琴音林的
 * 远景、竹雨庭的湿地面、花房的湖面），所以碎片栏的五个色块和进游戏后看到的
 * 那一屏是同一族颜色——玩家在 HUD 上认的是"颜色 + 汉字"，而颜色先到。
 *
 * ## 为什么比原来亮了一档
 *
 * 底色板从「宣纸」换成「深青蓝」之后，原来那套里有两格直接沉进背景里看不见了：
 * 竹那一格 #2e3a38 在深青蓝底上就是一个黑点，而茶那一格 #8a6540 只比背景亮一点。
 * 深底上颜色要**往亮处走**才读得出来，所以这里整体提了一档，
 * 保留原来的色相（天蓝 / 茶褐 / 琴绿 / 竹青 / 禽白）。
 *
 * ## 灰度可分性（这一条是可以算的，所以它就该成立）
 *
 * 相对亮度（`0.2126R + 0.7152G + 0.0722B`，按 sRGB 线性化前近似）：
 * 云 0.72 / 茶 0.44 / 琴 0.63 / 竹 0.37 / 禽 0.89。
 *
 * **相邻两槽的差都 ≥ 0.15**：0.28 / 0.19 / 0.25 / 0.52。
 * 差值不够的话，红绿色觉障碍者与全色盲看到的就会是"两个都是褐色"，
 * 而碎片栏是玩家判断"还差哪几件"的唯一依据。
 *
 * ⚠ 上一版的**两套**配色都不满足这一条（默认那套的茶/琴只差 0.02，
 * 色觉那套的琴/竹只差 0.03），而当时没有任何断言守着它——
 * 现在两套都改到满足为止，数字就写在这里。
 */
export const FRAGMENT_COLORS: readonly string[] = [
  '#7cc4f0', // 云
  '#9c6a33', // 茶
  '#7fae7a', // 琴
  '#3f6b4c', // 竹
  '#f2e3bd', // 禽
];

/**
 * 色觉友好的一套。**相邻两槽在灰度下也分得开**才是它存在的理由。
 *
 * ## 为什么不调默认那一套
 *
 * 默认配色是"五个地方的景"——它好看，而且和游戏里实际看到的那一屏同源。
 * 把它改成好看以外的东西，代价是所有玩家的第一眼都变了。
 * 所以它是**可选项**，默认不动。
 *
 * ## 灰度可分性
 *
 * 相对亮度（同上）：云 0.47 / 茶 0.70 / 琴 0.39 / 竹 0.59 / 禽 0.30。
 * 相邻槽的差：**0.23 / 0.31 / 0.20 / 0.30**，都 ≥ 0.15。
 */
export const FRAGMENT_COLORS_COLORBLIND: readonly string[] = [
  '#4d7fb0', // 云 · 亮蓝
  '#d9b23f', // 茶 · 亮黄
  '#7a56ad', // 琴 · 紫
  '#e08a3c', // 竹 · 橙
  '#585858', // 禽 · 中灰
];

/** 当前生效的那一套。**唯一读法**：谁也别自己去读两个常量。 */
export function fragmentColors(colorblind: boolean): readonly string[] {
  return colorblind ? FRAGMENT_COLORS_COLORBLIND : FRAGMENT_COLORS;
}

